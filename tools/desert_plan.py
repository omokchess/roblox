def lua(v):
    if isinstance(v, (list, tuple)):
        return "{ " + ", ".join(lua(x) for x in v) + " }"
    if isinstance(v, str):
        return '"%s"' % v
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def emit(path):
    out = ["-- desert_plan.py 가 만든 데이터(손으로 고치지 말고 표를 고칠 것)", "local TOP = %s" % TOP]
    for name, rows in (("LAND", LAND), ("CLIFFS", CLIFFS), ("SHORE", SHORE), ("MESAS", MESAS), ("CANYON", CANYON), ("DUNES", DUNES), ("ROCKS", ROCKS)):
        out.append("local %s = {" % name)
        out += ["\t%s," % lua(r) for r in rows]
        out.append("}")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


