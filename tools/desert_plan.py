def overlap(a, b, pad=0.0):
    return a[0] < b[2] + pad and b[0] < a[2] + pad and a[1] < b[3] + pad and b[1] < a[3] + pad


def rect(m):
    return (m[1], m[3], m[2], m[4])


def on_land(r):
    def on(x, z):
        return any(l[0] <= x <= l[1] and l[2] <= z <= l[3] for l in LAND)
    return all(on(x, z) for x, z in ((r[0], r[1]), (r[2], r[1]), (r[0], r[3]), (r[2], r[3])))


def box(r):
    return (r[0], r[2], r[1], r[3])


def check():
    probs = []
    rocks_big = [rect(m) for m in MESAS] + [box(c) for c in CANYON]
    no_rock = [rect(m) for m in MESAS] + [box(c) for c in CANYON[CANYON_MAIN:]] + [box(r) for r in RAMPS] + [box(b) for b in BRIDGES] + [box(l) for l in LEDGES] + [box(w) for w in WALL_ROCKS]
    dunes = [(box(d), d[4]) for d in DUNES]
    sites = [("신전 자리", (TEMPLE_SITE[0], TEMPLE_SITE[2], TEMPLE_SITE[1], TEMPLE_SITE[3])),
             ("마을 자리", (TOWN_SITE[0], TOWN_SITE[2], TOWN_SITE[1], TOWN_SITE[3]))]
    allboxes = [(r, None) for r in rocks_big] + dunes
    for r, _ in allboxes:
        if not on_land(r):
            probs.append("땅 밖: %s" % (r,))
        for site, sr in sites:
            if overlap(r, sr, 4):
                probs.append("%s 침범: %s" % (site, r))
    # 겹친 사구끼리 높이가 같으면 윗면이 깜박인다 · 이웃 높이 차 6 넘으면 못 오른다
    for i, (a, ha) in enumerate(dunes):
        for b, hb in dunes[i + 1:]:
            if overlap(a, b, 0):
                if ha == hb:
                    probs.append("겹친 사구 높이 같음: %s %s" % (a, b))
                if abs(ha - hb) > 6:
                    probs.append("사구 단차 6 넘음: %s %s" % (a, b))
    for i, rk in enumerate(ROCKS):
        h = max(rk[2], rk[4]) / 2
        r = (rk[0] - h, rk[1] - h, rk[0] + h, rk[1] + h)
        if not on_land(r):
            probs.append("바위 땅 밖: %d" % i)
        for br in no_rock:
            if overlap(r, br, 1):
                probs.append("돌덩이가 높은 바위·돌출·오르막·다리에 박힘: %d" % i)
        for site, sr in sites:
            if overlap(r, sr, 2):
                probs.append("돌덩이가 %s: %d" % (site, i))
    for f in FORMATIONS:
        w, d = f[3][0][0], f[3][0][1]
        r = (f[1] - w / 2, f[2] - d / 2, f[1] + w / 2, f[2] + d / 2)
        if not on_land(r):
            probs.append("탑바위 땅 밖: %s" % f[0])
        for br in no_rock:
            if overlap(r, br, 1):
                probs.append("탑바위가 바위·턱길·다리에 겹침: %s" % f[0])
        for site, sr in sites:
            if overlap(r, sr, 2):
                probs.append("탑바위가 %s: %s" % (site, f[0]))
        for i, rk in enumerate(ROCKS):
            h = max(rk[2], rk[4]) / 2
            if overlap(r, (rk[0] - h, rk[1] - h, rk[0] + h, rk[1] + h), 0):
                probs.append("탑바위가 돌덩이 %d 와 겹침: %s" % (i, f[0]))
    for i, a in enumerate(LAND):
        for b in LAND[i + 1:]:
            if overlap((a[0], a[2], a[1], a[3]), (b[0], b[2], b[1], b[3]), -0.01):
                probs.append("땅 판 겹침: %s ↔ %s" % (a, b))
    return probs


