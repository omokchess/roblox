def tip_y(P):
    return wpoint(P, "W", TIP)[1]


def two_fit(P, grip_t, dirxz, pitch_range, zhint_t, left_y=-0.6, want_tip=None, **kw):
    """날 방향 = 몸통 공간 수평 성분 dirxz(dx, dz) + 기울기. want_tip 이 있으면 칼끝 높이가 그 값에 가장 가깝게 기울기를 고른다"""
    best = None
    for pitch in pitch_range:
        p = math.radians(pitch)
        d = (dirxz[0] * math.cos(p), math.sin(p), dirxz[1] * math.cos(p))
        Q = dict(P)
        eR, eL, off = two_hand(Q, grip_t, d, zhint_t, left_y=left_y, **kw)
        ty = tip_y(Q)
        score = max(eR, eL) * 4 + (abs(ty - want_tip) if want_tip is not None else 0)
        if best is None or score < best[0]:
            best = (score, Q, pitch, eR, eL, ty)
    _, Q, pitch, eR, eL, ty = best
    P.update(Q)
    return f"(기울기 {pitch}°, 팔 어긋남 {eR}/{eL}, 칼끝 높이 {ty:.2f})"


def show(name, P, note=""):
    line = f"local {name} = {{ " + ", ".join(f"{k} = {f(P[k])}" for k in KEYS if k in P) + " }"
    print(f"-- {name} {note}")
    print(line)


