"""월 브레이커 자세 계산(2026-10-02). 조지 실버 쿼터스태프 — 뒷손(오른손)은 자루 끝 가죽(y 0.05),
앞손(왼손)은 그 1.3 위 가죽(y 1.35), 앞손·앞발(왼쪽)이 적 쪽, 낮은 겨눔(지팡이 끝이 적 얼굴 높이).
곡괭이 머리(y 4.0, 날 -Z)가 앞 끝. 방향은 월드(캐릭터 앞 = -Z)로 주고 몸통 공간으로 바꿔 two_hand 에 넘긴다."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from twohand import *

KEYS = ["Root", "Torso", "Head", "RArm", "LArm", "RLeg", "LLeg", "W"]
RY, LY = 0.05, 1.35  # 두 손이 쥐는 가죽 자리
TIP = (0, 3.75, -2.36)  # 곡괭이 날 끝
BUTT = (0, -1.73, 0)  # 물미 끝
REF = {}


def out(name, P, note=""):
    if "W" in REF:
        P["W"] = near(P["W"], REF["W"])
    tip, butt = wpoint(P, "W", TIP), wpoint(P, "W", BUTT)
    print(f"-- {name} {note} 날 끝 높이 {tip[1]:.2f} 물미 {butt[1]:.2f} (땅 -3)")
    print(f"local {name} = {{ " + ", ".join(f"{k} = {f(P[k])}" for k in KEYS if k in P) + " }")


def two_w(P, grip_t, dir_w, blade_w, ry=RY, ly=LY, hR=(70, 30, 0), hL=(70, -20, 0)):
    """월드 방향(지팡이 축 dir_w, 날 쪽 blade_w)을 몸통 공간으로 바꿔 두 손 쥠"""
    T = T_of(P)
    inv = tr(T.R)
    return two_hand(P, grip_t, mv(inv, dir_w), mv(inv, blade_w), left_y=ly, right_y=ry, hintR=hR, hintL=hL)


def body(root, torso, head, rleg=(-20, 0, 12), lleg=(24, 0, -12)):
    return {"Root": root, "Torso": torso, "Head": head, "RLeg": rleg, "LLeg": lleg}


if __name__ == "__main__":
    # 1) 낮은 겨눔(대기): 몸을 오른쪽으로 틀어 왼 어깨·왼발이 적 쪽, 두 손은 허리 앞, 지팡이 끝은 적 얼굴 높이로 조금 들림,
    #    곡괭이 날은 아래(갈고리처럼 걸어 당길 준비)
    P = body((0, -0.45, 0, 0, -35, 0), (-12, 0, 0), (4, 30, 0))
    print(two_w(P, (0.1, -0.5, -1.0), (0, 0.18, -1), (0, -1, -0.2)))
    REF["W"] = P["W"]
    out("GUARD", P)
    # 1b) 찌르기 끝(대기 중 툭 찔러 봄): 앞으로 무게를 싣고 두 팔을 뻗음
    J = body((0, -0.55, -0.5, 0, -35, 0), (-20, 0, 0), (10, 30, 0), (-34, 0, 12), (36, 0, -12))
    print(two_w(J, (0.1, -0.2, -1.3), (0, 0.12, -1), (0, -1, -0.2), hR=(80, 30, 0), hL=(90, -20, 0)))
    out("JAB", J)
    # 2) 머리 위로 치켜듦(내려찍기 예비): 두 손을 머리 위로, 지팡이는 머리 위에서 뒤로 기울고 날은 위(내려칠 때 앞장섬)
    H = body((0, -0.1, 0.3, 0, -14, 0), (16, 0, 0), (16, 10, 0), (10, 0, 14), (-20, 0, -14))
    print(two_w(H, (0.2, 1.6, -0.4), (0, 0.6, 1), (0, 1, -0.3), hR=(170, 20, 0), hL=(170, -20, 0)))
    out("HIGH", H)
    # 3) 내려찍은 끝: 날 끝이 앞 땅(적 정수리 높이 아래)에 닿음
    K_ = body((0, -0.95, -0.6, 0, -12, 0), (-40, 0, 0), (24, 8, 0), (44, 0, 14), (-36, 0, -14))
    print(two_w(K_, (0.1, 0.4, -1.2), (0, 0.2, -1), (0, -1, 0), hR=(90, 20, 0), hL=(90, -20, 0)))
    out("PICK", K_)
    # 4) 막기: 지팡이를 가로로 머리 위에 들어 받음(두 손을 넓게)
    B = body((0, -0.7, 0.2, 0, -14, 0), (-6, 0, 0), (10, 10, 0), (20, 0, 14), (-16, 0, -14))
    print(two_w(B, (0.6, 1.5, -0.9), (-1, 0.05, 0), (0, 1, 0), ry=-0.3, ly=1.7, hR=(140, 10, 20), hL=(140, -10, -20)))
    out("BLOCK", B)
    # 5) 휩쓸기: 두 손을 자루 끝으로 미끄러뜨려 모아 쥐고 지팡이를 앞으로 수평으로 길게 뻗음(날은 오른쪽 = 몸이 오른쪽으로
    #    돌며 휩쓸 때 앞장서는 쪽). 휩쓸기는 Root 돌기로 몸째 돌린다
    S = body((0, -0.6, 0.2, 0, -18, 0), (-10, 0, 0), (10, 20, 0), (34, 0, 18), (-28, 0, -18))
    print(two_w(S, (0.2, -0.4, -1.1), (0.3, -0.05, -1), (1, 0, 0), ry=-1.3, ly=-0.6, hR=(70, 20, 0), hL=(70, -20, 0)))
    out("SWEEP", S)
    # 6) 짚고 기댐(명상·내려놓임): 지팡이를 오른발 앞에 세워 물미를 땅에, 두 손은 가슴 높이
    M = body((0, -0.15, 0, 0, -18, -4), (0, 0, 4), (-16, 10, 8), (6, 0, 4), (-4, 0, -10))
    print(two_w(M, (0.5, -0.8, -1.1), (0.05, 1, -0.1), (0, 0, -1), ry=1.2, ly=2.0, hR=(60, 20, 0), hL=(70, -20, 0)))
    out("LEAN", M)
    # 7) 제 가슴 치기: 자루를 가로로 두 손에 쥐고 가슴에 끌어당김
    C = body((0, -0.5, 0.4, 0, -18, 0), (-20, 0, 0), (-14, 16, 0))
    print(two_w(C, (0.0, 0.3, -0.75), (-1, 0.1, -0.1), (0, 1, 0), ry=-0.3, ly=1.7, hR=(40, 30, 10), hL=(40, -30, -10)))
    out("CHEST", C)
