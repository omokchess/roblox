from twohand import *

REF = (0, 0, 0, 0, 0, 0)
LEGS = {"RLeg": (30, 0, 18), "LLeg": (-24, 0, -18)}


def body(root, torso, head, legs=None):
    P = {"Root": root, "Torso": torso, "Head": head}
    P.update(legs or LEGS)
    return P


def two(name, P, grip, d, z, ry, ly, hR, hL, ref):
    r = two_hand(P, grip, d, z, left_y=ly, right_y=ry, hintR=hR, hintL=hL)
    P["W"] = near(P["W"], ref)
    show(name, P, str(r))
    return P["W"]


