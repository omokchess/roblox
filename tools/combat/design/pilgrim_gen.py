from twohand import *

KEYS = ["Root", "Torso", "Head", "RArm", "LArm", "RLeg", "LLeg", "W", "O"]


def emit(name, P, wdir, odir, ref=None):
    T = T_of(P)
    P["W"] = aim_axis(P, "W", mv(T.R, wdir))
    P["O"] = aim_axis(P, "O", mv(T.R, odir))
    if ref:
        P["W"] = near(P["W"], ref[0])
        P["O"] = near(P["O"], ref[1])
    print(f"local {name} = {{ " + ", ".join(f"{k} = {f(P[k])}" for k in KEYS if k in P) + " }")
    return P["W"], P["O"]


def fists(P, r, l, hr=(80, 30, 0), hl=(80, -30, 0)):
    T = T_of(P)
    P["RArm"], er = reach(P, "R", T.pt(r), hint=hr)
    P["LArm"], el = reach(P, "L", T.pt(l), hint=hl)
    return round(er, 2), round(el, 2)


