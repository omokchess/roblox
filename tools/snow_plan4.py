def walkable(k):
    return k in (K_GROUND, K_TERR, K_SLAB, K_STEP, K_PAVE)


def gap_scan(g):
    """같은 바닥(이웃 칸끼리 1 이하)이 양쪽 '솟은 것'(1 넘게 높아짐) 사이에 3~9 칸 — 가로·세로 줄마다"""
    found = []
    seen = set()
    for axis in ("u", "v"):
        lines = NV if axis == "u" else NU
        n = NU if axis == "u" else NV
        for L in range(lines):
            def h(i):
                return g.H[L][i] if axis == "u" else g.H[i][L]

            def k(i):
                return g.K[L][i] if axis == "u" else g.K[i][L]
            i = 1
            while i < n:
                if walkable(k(i)) and h(i - 1) > h(i) + 1.0:
                    j = i + 1
                    while j < n and walkable(k(j)) and abs(h(j) - h(j - 1)) <= 1.0:
                        j += 1
                    if j < n and h(j) > h(j - 1) + 1.0 and 3 <= j - i <= 9:
                        u, v = (U0 + i, V0 + L) if axis == "u" else (U0 + L, V0 + i)
                        key = (axis, round(u / 12), round(v / 12))
                        if key not in seen:
                            seen.add(key)
                            found.append((u, v, j - i, "동서" if axis == "u" else "남북"))
                    i = j
                else:
                    i += 1
    return found


def is_empty(g, i, j):
    return g.K[j][i] in (K_GROUND, K_TERR, K_SLAB) and g.PATH[j][i] is None


def empty_flats(g, side=41):
    """한 변 40 넘는 같은 높이 빈 정사각형. 겹친 것은 하나로"""
    prev = [0] * NU
    hits = []
    for j in range(NV):
        cur = [0] * NU
        Hj, Hp = g.G[j], g.G[j - 1] if j else None
        for i in range(NU):
            if not is_empty(g, i, j):
                continue
            if i and j and is_empty(g, i - 1, j) and is_empty(g, i, j - 1) and is_empty(g, i - 1, j - 1) and \
                    Hj[i] == Hj[i - 1] == Hp[i] == Hp[i - 1]:
                cur[i] = min(prev[i], cur[i - 1], prev[i - 1]) + 1
            else:
                cur[i] = 1
            if cur[i] >= side:
                hits.append((U0 + i - cur[i] + 1, V0 + j - cur[i] + 1, cur[i]))
        prev = cur
    out = []
    for u, v, s in sorted(hits, key=lambda t: -t[2]):
        if all(abs(u - a) > 30 or abs(v - b) > 30 for a, b, _ in out):
            out.append((u, v, s))
    return out


def sight_block(g, p):
    c = g.at(p[0], p[1])
    if c is None:
        return None
    eye = BASE + g.G[c[1]][c[0]] + EYE
    L = math.hypot(p[0], p[1])
    if L < 1:
        return None
    n = int(L)
    for t in range(1, n - 12):
        u, v = p[0] * (1 - t / L), p[1] * (1 - t / L)
        q = g.at(u, v)
        if q is None:
            continue
        if g.K[q[1]][q[0]] in (K_ROCK, K_TERR, K_SLAB, K_WALL):
            y = eye + (TOWER_TOP - eye) * t / L
            if BASE + g.H[q[1]][q[0]] >= y:
                return (u, v)
    return None


