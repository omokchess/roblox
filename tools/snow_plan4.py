def emit(g, path):
    lines = [HEADER.rstrip("\n"), "local D = {}"]

    def table(name, rows):
        lines.append("D.%s = {" % name)
        for r in rows:
            lines.append("\t" + lua(list(r)) + ",")
        lines.append("}")
    pads = []
    for name, u, v, yaw, h, fore, no, kr in PADS:
        x, z = to_world(u, v)
        du, dv = pad_door(name, u, v, yaw)
        pads.append((name, x, z, yaw, BASE + h, fore) + to_world(du, dv) + (no, kr))
    table("PADS", pads)
    table("KEEP", KEEP)
    table("TERRACES", [(t[0],) + to_world(t[1], 0)[:1] + to_world(t[2], 0)[:1] + (CZ + t[3], CZ + t[4], BASE + t[5], t[6]) for t in TERRACES])
    table("STEPS", [(s[0], CX + s[1], CX + s[2], CZ + s[3], CZ + s[4], BASE + s[5]) for s in STEPS])
    table("PATHS", [(n, w, [to_world(*p) for p in pts]) for n, w, pts in PATHS])
    table("PATH_PIECES", path_pieces(g))
    table("ROCKS", [(CX + b[0], CX + b[1], CZ + b[2], CZ + b[3], BASE + b[4], i + 1, ROCKS[i][0]) for i, b in ALL_ROCKS])
    table("SLABS", [(CX + s[0], CX + s[1], CZ + s[2], CZ + s[3], BASE + s[4]) for s in SLABS])
    props = []
    for k, u, v, yaw, s in PROPS:
        q = g.at(u, v)
        props.append((k,) + to_world(u, v) + (BASE + (g.G[q[1]][q[0]] if q else 0.0), yaw, s))
    table("PROPS", props)
    mast = [p for p in PADS if p[0] == "Sn3_Mast"][0]
    lines.append("D.AIRSHIP = %s" % lua(list(to_world(mast[1], mast[2] + 38.0)) + [mast[3], 25.4]))
    lines.append("D.KEEP_FOLDERS = %s" % lua([k for k, _ in KEEP_FOLDERS]))
    lines.append("D.REMOVE_FOLDERS = %s" % lua(REMOVE_FOLDERS))
    lines.append('D.BACKUP = "%s"' % BACKUP)
    lines.append("return D")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


