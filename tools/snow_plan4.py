# ------------------------------------------------------------------ Luau
def lua(v):
    if isinstance(v, str):
        return '"' + v + '"'
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return ("%.2f" % v).rstrip("0").rstrip(".")
    return "{" + ", ".join(lua(x) for x in v) + "}"


def path_pieces(g):
    """길 토막을 바닥 높이가 같은 조각으로 — (이름, 폭, x0, z0, x1, z1, 윗면 y)"""
    out = []
    for name, w, pts in PATHS:
        for a, b in zip(pts, pts[1:]):
            smp, L = seg_samples(a, b, 0.5)
            run0, hcur = smp[0], None
            for k, p in enumerate(smp):
                q = g.at(min(p[0], U1 - 1), min(p[1], V1 - 1))
                hh = g.G[q[1]][q[0]] if q else 0.0
                if hcur is None:
                    hcur = hh
                if abs(hh - hcur) > 1e-6:
                    out.append((name, w) + to_world(*run0) + to_world(*p) + (BASE + hcur,))
                    run0, hcur = p, hh
            out.append((name, w) + to_world(*run0) + to_world(*b) + (BASE + hcur,))
    return [o for o in out if math.hypot(o[4] - o[2], o[5] - o[3]) > 0.1]


