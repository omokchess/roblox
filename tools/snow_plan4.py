def template_sides(k):
    bs = ROCK_T[k]
    x1 = max(b[0] + b[2] for b in bs)
    z1 = max(b[1] + b[3] for b in bs)
    nx, nz = int(math.ceil(x1 / SIDE_RES)) + 2, int(math.ceil(z1 / SIDE_RES)) + 2
    H = [[0.0] * nx for _ in range(nz)]
    for x, z, w, d, h in bs:
        for j in range(int(round(z / SIDE_RES)) + 1, int(round((z + d) / SIDE_RES)) + 1):
            row = H[j]
            for i in range(int(round(x / SIDE_RES)) + 1, int(round((x + w) / SIDE_RES)) + 1):
                if h > row[i]:
                    row[i] = h
    top = max(b[4] for b in bs)

    def side(lines):
        rises = []
        for line in lines:
            best, prev = 0.0, 0.0
            for h in line:
                if h > prev:
                    best = max(best, h - prev)
                prev = h
            if any(line):
                rises.append(best)
        rises.sort()
        return rises[int(0.9 * (len(rises) - 1))] if rises else 0.0
    cols = [[H[j][i] for j in range(nz)] for i in range(nx)]
    return top, {"북": side(cols), "남": side([c[::-1] for c in cols]), "서": side(H), "동": side([r[::-1] for r in H])}


