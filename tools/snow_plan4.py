def path_graph():
    """꼭짓점·T 이음을 마디로. 광장 안 꼭짓점은 광장 가운데와 곧게 잇는다"""
    segs = []
    for name, w, pts in PATHS:
        for a, b in zip(pts, pts[1:]):
            segs.append((tuple(a), tuple(b)))
    verts = {p for s in segs for p in s}
    adj = {}

    def link(p, q):
        d = math.hypot(p[0] - q[0], p[1] - q[1])
        adj.setdefault(p, []).append((q, d))
        adj.setdefault(q, []).append((p, d))
    for a, b in segs:
        on = [a, b] + [p for p in verts if p not in (a, b) and P2.seg_dist(p[0], p[1], a, b) < 0.5]
        on.sort(key=lambda p: (p[0] - a[0]) ** 2 + (p[1] - a[1]) ** 2)
        for p, q in zip(on, on[1:]):
            link(p, q)
    o = (0.0, 0.0)
    for p in verts:
        if abs(p[0]) <= 40.01 and abs(p[1]) <= 40.01:
            link(o, p)
    dist = {o: 0.0}
    pq = [(0.0, o)]
    while pq:
        d, p = heapq.heappop(pq)
        if d > dist.get(p, 1e18):
            continue
        for q, w in adj.get(p, []):
            if d + w < dist.get(q, 1e18):
                dist[q] = d + w
                heapq.heappush(pq, (d + w, q))
    return dist


def walk_table():
    dist = path_graph()
    rows = []
    for name, no, kr, poly, door, kept in pad_entries():
        if name == "Sn3_Clock":
            continue
        best = None
        for p, d in dist.items():
            e = math.hypot(p[0] - door[0], p[1] - door[1])
            if e <= 12.0 and (best is None or d + e < best[0]):
                best = (d + e, e)
        if name == "Figuren_HQ" and best is None:        # 길 끝(연병장 북쪽 가)에서 판을 건너 문으로
            for p, d in dist.items():
                e = math.hypot(p[0] - door[0], p[1] - door[1])
                if e <= 70.0 and (best is None or d + e < best[0]):
                    best = (d + e, e)
        lim = 480.0 if (kept or name == "Sn3_Gate") else 160.0
        rows.append((no, name, kr, best[0] if best else None, lim))
    return sorted(rows)


