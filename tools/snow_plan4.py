def keep_door(kind, x, z, yaw):
    fx, fz = front(yaw)
    d = -P2.KIT[kind][0][2]
    return (round(x - CX + fx * d, 2), round(z - CZ + fz * d, 2))


def rock_boxes(row):
    """본보기 놓기 한 줄 → 상자 [(u0, u1, v0, v1, 윗면 h)]"""
    k, u, v, rot, mir, sc, base = row
    out = []
    for x, z, w, d, h in ROCK_T[k]:
        x0, x1, z0, z1 = x * sc, (x + w) * sc, z * sc, (z + d) * sc
        if mir:
            x0, x1 = -x1, -x0
        for _ in range((rot // 90) % 4):            # 시계 90: (x, z) → (-z, x)  ('뒤' 북 → 동)
            x0, x1, z0, z1 = -z1, -z0, x0, x1
        out.append([x0, x1, z0, z1, base + h * sc])
    mx, mz = min(b[0] for b in out), min(b[2] for b in out)
    return [(round(u + b[0] - mx, 2), round(u + b[1] - mx, 2), round(v + b[2] - mz, 2), round(v + b[3] - mz, 2), round(b[4], 2)) for b in out]


