def pad_depth(name):
    """피벗에서 앞(문)·뒤까지 (앞, 뒤). 보통 깊이의 반씩 — FRONT_BACK 에 적힌 건물만 다르다"""
    return FRONT_BACK.get(name, (SIZE[name][1] / 2, SIZE[name][1] / 2))


def pad_rect(name, u, v, yaw):
    w = SIZE[name][0]
    f, b = pad_depth(name)
    r = math.radians(yaw)
    c, s = math.cos(r), math.sin(r)
    pts = [(u + lx * c + lz * s, v - lx * s + lz * c) for lx in (-w / 2, w / 2) for lz in (-f, b)]
    return (min(p[0] for p in pts), max(p[0] for p in pts), min(p[1] for p in pts), max(p[1] for p in pts))


def front(yaw):
    r = math.radians(yaw)
    return -math.sin(r), -math.cos(r)


def pad_door(name, u, v, yaw):
    fx, fz = front(yaw)
    d = pad_depth(name)[0]
    return (round(u + fx * d, 2), round(v + fz * d, 2))


