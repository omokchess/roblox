def face_runs(g, thr):
    """바위 면 조각(칸 경계)을 같은 줄·같은 윗면 높이·솟음 > thr 로 이어 (방향, u, v, 길이, 가장 큰 솟음, 걷는 땅 앞?) 목록"""
    out = []
    for d, (di, dj) in (("북", (0, -1)), ("남", (0, 1)), ("서", (-1, 0)), ("동", (1, 0))):
        along = (1, 0) if dj else (0, 1)
        seen = set()
        for j in range(1, NV - 1):
            for i in range(1, NU - 1):
                if (i, j) in seen or g.K[j][i] != K_ROCK:
                    continue
                h = g.H[j][i]
                rise, walk_front, L = 0.0, False, 0
                ci, cj = i, j
                while 0 < ci < NU - 1 and 0 < cj < NV - 1 and g.K[cj][ci] == K_ROCK and abs(g.H[cj][ci] - h) < 1e-6:
                    m = (ci + di, cj + dj)
                    r2 = h - g.H[m[1]][m[0]]
                    if r2 <= thr or g.K[m[1]][m[0]] in (K_OUT, K_WALL):
                        break
                    seen.add((ci, cj))
                    rise = max(rise, r2)
                    walk_front = walk_front or walkable(g.K[m[1]][m[0]])
                    L += 1
                    ci, cj = ci + along[0], cj + along[1]
                if L:
                    out.append((d, U0 + i, V0 + j, L, round(rise, 1), walk_front))
    return out


GAP_MIN = 1   # 2판: 1~2 칸 틈(바위 사이 끼인 눈 줄)도 막는다 — 걸을 수도 없고 재는 자리가 벽에 붙는다


def gap_scan(g):
    """같은 바닥(이웃 칸끼리 1 이하)이 양쪽 '솟은 것'(1 넘게 높아짐) 사이에 3~9 칸 — 가로·세로 줄마다"""
    found = []
    seen = set()
    for axis in ("u", "v"):
        lines = NV if axis == "u" else NU
        n = NU if axis == "u" else NV
        for L in range(lines):
            def h(i):
                return g.H[L][i] if axis == "u" else g.H[i][L]

            def k(i):
                return g.K[L][i] if axis == "u" else g.K[i][L]
            i = 1
            while i < n:
                if walkable(k(i)) and h(i - 1) > h(i) + 1.0:
                    j = i + 1
                    while j < n and walkable(k(j)) and abs(h(j) - h(j - 1)) <= 1.0:
                        j += 1
                    if j < n and h(j) > h(j - 1) + 1.0 and GAP_MIN <= j - i <= 9:
                        u, v = (U0 + i, V0 + L) if axis == "u" else (U0 + L, V0 + i)
                        key = (axis, round(u / 12), round(v / 12))
                        if key not in seen:
                            seen.add(key)
                            found.append((u, v, j - i, "동서" if axis == "u" else "남북"))
                    i = j
                else:
                    i += 1
    return found


def is_empty(g, i, j):
    return g.K[j][i] in (K_GROUND, K_TERR, K_SLAB) and g.PATH[j][i] is None


