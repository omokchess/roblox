def cells(u0, u1, v0, v1):
    a, b = max(0, int(math.floor(u0 - U0 + 0.5))), min(NU, int(math.floor(u1 - U0 + 0.5)))
    c, d = max(0, int(math.floor(v0 - V0 + 0.5))), min(NV, int(math.floor(v1 - V0 + 0.5)))
    return range(a, b), range(c, d)


def in_poly(poly, x, z):
    hit = False
    n = len(poly)
    for i in range(n):
        (ax, az), (bx, bz) = poly[i], poly[(i + 1) % n]
        if (az > z) != (bz > z) and x < ax + (z - az) * (bx - ax) / (bz - az):
            hit = not hit
    return hit


class Grid:
    def __init__(self):
        self.H = [[0.0] * NU for _ in range(NV)]       # 걷는 윗면 h(바위·건물 포함)
        self.G = [[0.0] * NU for _ in range(NV)]       # 바닥 h(단·판·넓은 단까지 — 바위·건물 빼고)
        self.K = [[K_OUT] * NU for _ in range(NV)]
        self.PATH = [[None] * NU for _ in range(NV)]
        self.FLAT = [[False] * NU for _ in range(NV)]  # 마을 고원 위(땅 json 평지)
        for j in range(NV):
            for i in range(NU):
                u, v = U0 + i + 0.5, V0 + j + 0.5
                h = P2.ground_at(CX + u, CZ + v)
                mine = (-394 <= u <= 383 and -307 <= v <= 211) or (383 <= u <= 457 and 38 <= v <= 211)   # 사양 고원 + 동문 길 띠
                if not mine and h is not None and 59.4 <= h <= 60.3:
                    h = None                                   # 마을 밖 평지(남쪽 59.9 띠·필드) — 손대지 않는다
                if h is None or h < 59.4:
                    self.K[j][i], self.H[j][i] = K_OUT, -50.0
                elif h > 60.3:
                    self.K[j][i], self.H[j][i] = K_WALL, h - BASE      # 서·북 높은 바위
                else:
                    self.K[j][i] = K_GROUND
                    self.FLAT[j][i] = True

    def floor(self, u0, u1, v0, v1, h, kind):
        ii, jj = cells(u0, u1, v0, v1)
        for j in jj:
            Hj, Gj, Kj = self.H[j], self.G[j], self.K[j]
            for i in ii:
                if Kj[i] in (K_OUT, K_WALL):
                    continue
                if kind == K_TERR or h >= Gj[i]:
                    Gj[i] = Hj[i] = h
                    Kj[i] = kind

    def solid(self, u0, u1, v0, v1, top, kind):
        ii, jj = cells(u0, u1, v0, v1)
        for j in jj:
            Hj, Kj = self.H[j], self.K[j]
            for i in ii:
                if Kj[i] in (K_OUT, K_WALL):
                    continue
                if top > Hj[i] or kind in (K_BLD, K_KEEP):
                    Hj[i] = max(top, Hj[i])
                    Kj[i] = kind

    def at(self, u, v):
        i, j = int(math.floor(u - U0)), int(math.floor(v - V0))
        if 0 <= i < NU and 0 <= j < NV:
            return i, j
        return None


def seg_samples(a, b, step=1.0):
    L = math.hypot(b[0] - a[0], b[1] - a[1])
    n = max(1, int(L / step))
    return [(a[0] + (b[0] - a[0]) * t / n, a[1] + (b[1] - a[1]) * t / n) for t in range(n + 1)], L


