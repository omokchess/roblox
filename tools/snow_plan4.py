def empty_flats(g, side=41):
    """한 변 40 넘는 같은 높이 빈 정사각형(나무 둘레 TREE_R 안은 빈 땅 아님). 겹친 것은 하나로"""
    tree = set()
    for k, u, v, yaw, s in PROPS:
        if k == "Gas_Lamp":
            continue
        r = int(TREE_R)
        for du in range(-r, r + 1):
            for dv in range(-r, r + 1):
                if du * du + dv * dv <= TREE_R * TREE_R:
                    c = g.at(u + du, v + dv)
                    if c:
                        tree.add(c)

    def is_empty(g, i, j):
        return (i, j) not in tree and g.K[j][i] in (K_GROUND, K_TERR, K_SLAB) and g.PATH[j][i] is None
    prev = [0] * NU
