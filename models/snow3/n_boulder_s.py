"""
n_boulder_s.py — 2026-11-17. 설원 3판 자연 키트: 작은 바위(5 × 4 × 3.5). 모서리 따낸 판 둘(아래 RockA 큰 판 · 위 RockB 조각이 18° 돌아 얹힘)
+ 위 조각 윗면 눈 + 아래 판 드러난 턱 눈. 판 둘레(위에서 본 다각형)·기울기·눈 자리는 손 표. 밑 판은 밑이 넓어(foot > 1) 땅에 앉고, 얹힌 판은 밑이 좁아(foot < 1) 얹혀 보인다.
"""
import lib_n as N

NAME = "Sn3_Boulder_S"
PREFIX = "Sn3BoulderS"

# (재질, 둘레, z0, z1, 모서리 따냄, 밑 배수, 윗면 배수, 기울임(rx, ry, rz, 옮김), 눈(s, off, te, tc) 또는 None)
SLABS = [
    ("RockA", [(-2.3, -1.2), (-0.9, -1.85), (1.4, -1.7), (2.45, -0.6), (2.1, 1.1), (0.6, 1.85), (-1.6, 1.5), (-2.45, 0.3)],
     -0.5, 2.4, 0.6, 1.04, 0.78, (4, -5, 0, (0, 0, 0)), (0.66, (0.55, -0.3), 0.28, 0.36)),
    ("RockB", [(-1.3, -0.9), (0.4, -1.15), (1.5, -0.25), (1.15, 0.95), (-0.45, 1.15), (-1.45, 0.3)],
     1.9, 3.15, 0.4, 0.95, 0.75, (0, 7, 18, (-0.4, 0.25, 0)), (0.78, (0.05, 0.05), 0.28, 0.36)),
]


def build(g):
    for mat, poly, z0, z1, cham, foot, top, (rx, ry, rz, t), snow in SLABS:
        pts = N.slab(g, mat, poly, z0, z1, cham, foot, top, N.rot(rx, ry, rz, t))
        if snow:
            s, off, te, tc = snow
            N.slab_snow(g, pts, s=s, off=off, te=te, tc=tc)
    N.cbox(-2.1, 2.1, -1.5, 1.5, 0, 2.9)
