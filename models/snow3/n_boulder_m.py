import lib_n as N

NAME = "Sn3_Boulder_M"
PREFIX = "Sn3BoulderM"

SLABS = [
    ("RockC", [(-4.6, -2.6), (-2.2, -3.9), (1.6, -3.8), (4.5, -2.4), (4.9, 0.6), (3.2, 3.6), (-0.6, 3.95), (-3.8, 3.0), (-4.95, 0.4)],
     -0.6, 2.6, 0.7, 1.05, 0.86, (-3, 2, 0, (0, 0, 0)), (0.6, (0.6, -1.8), 0.32, 0.42)),
    ("RockA", [(-3.3, -2.2), (-0.8, -2.9), (2.4, -2.3), (3.4, 0.1), (2.2, 2.5), (-1.0, 2.8), (-3.4, 1.4)],
     2.0, 4.7, 0.6, 0.93, 0.80, (4, -3, 22, (-0.5, 0.9, 0)), (0.66, (0.6, -0.9), 0.32, 0.42)),
    ("RockB", [(-1.8, -1.2), (0.3, -1.6), (1.9, -0.6), (1.6, 1.1), (-0.2, 1.5), (-1.9, 0.6)],
     4.1, 5.55, 0.45, 0.95, 0.76, (-6, 5, -15, (0.6, 1.6, 0)), (0.8, (0.0, 0.0), 0.32, 0.42)),
]


def build(g):
    for mat, poly, z0, z1, cham, foot, top, (rx, ry, rz, t), snow in SLABS:
        pts = N.slab(g, mat, poly, z0, z1, cham, foot, top, N.rot(rx, ry, rz, t))
        if snow:
            s, off, te, tc = snow
            N.slab_snow(g, pts, s=s, off=off, te=te, tc=tc)
    N.cbox(-4.5, 4.5, -3.4, 3.4, 0, 2.5)
    N.cbox(-3.4, 2.8, -1.6, 3.4, 2.5, 5.2)
