import lib_n as N

NAME = "Sn3_Bush"
PREFIX = "Sn3Bush"

# (재질, 밑 가운데, rx, ry, 높이, 윗고리 배수, 아랫고리 배수, 돌림, 눈 덮는 비율)
LUMPS = [
    ("Needle", (-0.6, 0.25, -0.3), 2.4, 2.25, 3.0, (1.00, 0.85, 0.95, 0.80, 1.05, 0.90, 0.88), (0.95, 1.00, 0.85, 0.98, 0.90, 1.00, 0.92), 0.2,
     (0.75, 0.55, 0.80, 0.50, 0.70, 0.60, 0.78)),
    ("NeedleLit", (1.6, -0.6, -0.3), 1.45, 1.35, 2.4, (1.00, 0.86, 0.96, 0.84, 1.02, 0.90), (0.92, 1.00, 0.88, 0.96, 0.90, 1.00), 0.6,
     (0.70, 0.50, 0.75, 0.55, 0.68, 0.60)),
    ("Needle", (0.9, 1.5, -0.3), 1.3, 1.1, 1.9, (0.95, 1.00, 0.86, 0.98, 0.88, 1.02), (1.00, 0.90, 0.95, 0.86, 1.00, 0.92), 1.0,
     (0.65, 0.50, 0.70, 0.48, 0.62, 0.55)),
]
SPRIGS = [((-1.4, -0.6, 1.6), (-1.9, -1.1, 2.8)), ((0.2, 1.0, 2.0), (0.4, 1.4, 2.95)), ((1.3, -0.4, 1.4), (1.9, -0.9, 2.4)),
          ((-2.0, 0.9, 1.2), (-2.7, 1.3, 2.0)), ((0.6, 1.9, 1.1), (1.0, 2.5, 1.9))]


def build(g):
    for mat, c, rx, ry, h, up, lo, rot, fr in LUMPS:
        top, ring = N.gem(g, mat, c, rx, ry, h, up, lo, rot)
        N.snow_cap(g, top, ring, fr, sink=0.1, tc=0.35, te=0.22, push=0.12)
    for p0, p1 in SPRIGS:
        N.stick(g, "Needle", p0, p1, 0.18, 0, n=3, tip=True)
    N.cbox(-2.6, 2.6, -1.6, 2.1, 0, 2.2)
