"""
n_woodpile.py — 2026-11-17. 설원 3판 자연 키트: 장작 더미(6 × 3 × 4). 짙은 받침목 둘 위에 6각 장작 세 줄(6·5·4개, 켠 면이 앞 -y 로)
— 장작 끝은 하나하나 앞뒤로 조금씩 들쭉날쭉(손 표) · 장작 사이 틈으로 속의 짙은 껍질 덩이가 그늘처럼 보인다.
네 기둥(DarkLog)이 받친 외쪽 지붕(앞이 낮음, 판자 셋 Timber) + 지붕 눈(판자와 평행, 0.06 묻힘).
"""
import math

import lib_n as N
from lib import bx

NAME = "Sn3_Woodpile"
PREFIX = "Sn3Woodpile"

LR = 0.42                                                           # 장작 반지름(6각)
ROWS = [  # (높이, [(x, 앞 y, 뒤 y)])
    (0.67, [(-2.30, -1.42, 1.30), (-1.38, -1.36, 1.24), (-0.46, -1.47, 1.33), (0.46, -1.33, 1.27), (1.38, -1.44, 1.22), (2.30, -1.38, 1.31)]),
    (1.41, [(-1.84, -1.35, 1.26), (-0.92, -1.46, 1.32), (0.0, -1.40, 1.23), (0.92, -1.31, 1.29), (1.84, -1.43, 1.35)]),
    (2.15, [(-1.38, -1.39, 1.25), (-0.46, -1.45, 1.30), (0.46, -1.34, 1.22), (1.38, -1.41, 1.33)]),
]
PX, PY0, PY1 = 2.98, -1.2, 1.15                                     # 기둥 x · 앞 y · 뒤 y
PZ_F, PZ_B = 2.8, 3.25                                              # 기둥 머리 높이(앞 · 뒤)
YC, YL = -0.02, 3.1                                                 # 지붕 가운데 y · 판 길이


def build(g):
    for y in (-0.95, 0.95):
        bx(g, "DarkLog", -2.75, 2.75, y - 0.2, y + 0.2, -0.25, 0.3)
    bx(g, "Bark", -2.5, 2.5, -1.0, 1.0, 0.15, 2.2)                  # 속(틈으로 보이는 그늘) — 밑은 받침목 사이, 장작 밑면과 겹치지 않게
    for z, logs in ROWS:
        for x, y0, y1 in logs:
            N.stick(g, "Wood", (x, y0, z), (x, y1, z), LR, LR, n=6)
    for x in (-PX, PX):
        bx(g, "DarkLog", x - 0.15, x + 0.15, PY0 - 0.15, PY0 + 0.15, -0.6, PZ_F)
        bx(g, "DarkLog", x - 0.15, x + 0.15, PY1 - 0.15, PY1 + 0.15, -0.6, PZ_B)
    a = math.atan2(PZ_B - PZ_F, PY1 - PY0)
    zr = PZ_F + (YC - PY0) * math.tan(a)                            # 기둥 머리 선의 YC 높이
    n = (0.0, -math.sin(a), math.cos(a))                            # 지붕 법선

    def along(d):
        return YC + n[1] * d, zr + n[2] * d
    for x in (-PX, PX):                                             # 서까래(기둥 머리 위)
        y, z = along(0.15)
        g["DarkLog"].obox(x, y, z, 0.3, YL, 0.3, rx=a)
    planks = ((-2.08, 0.18), (0.0, 0.2), (2.08, 0.17))              # 판자 셋(두께 다르게), 밑은 서까래 속 0.03
    for x, th in planks:
        y, z = along(0.27 + th / 2)
        g["Timber"].obox(x, y, z, 2.04, YL, th, rx=a)
    y, z = along(0.27 + min(th for _, th in planks) - 0.06 + 0.17)   # 눈: 가장 낮은 판 윗면 아래 0.06 에서 두께 0.34
    g["SnowCap"].obox(0.0, y, z, 6.0, YL - 0.2, 0.34, rx=a)
    N.cbox(-3.1, 3.1, -1.5, 1.35, 0, 3.0)
