def _at(rings, z):
    """줄기 고리 사이(밖이면 늘여서) z 높이의 가운데·반지름"""
    i = next((k for k in range(len(rings) - 1) if z <= rings[k + 1][2]), len(rings) - 2)
    a, b = rings[i], rings[i + 1]
    t = (z - a[2]) / (b[2] - a[2])
    return a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1]), a[3] + t * (b[3] - a[3])


def _hex(rings, z, dr, ks=range(6), inner=None):
    x, y, r = _at(rings, z)
    pts = [(x + (r + dr) * math.cos(math.pi * k / 3), y + (r + dr) * math.sin(math.pi * k / 3), z) for k in ks]
    if inner is not None:
        pts += [(x + (r - inner) * math.cos(math.pi * k / 3), y + (r - inner) * math.sin(math.pi * k / 3), z) for k in reversed(ks)]
    return pts


def _fan(g, p, az0, fan, s):
    for daz, el, ln, r in fan:
        a, e, L_ = math.radians(az0 + daz), math.radians(el), ln * s
        N.stick(g, "Twig", p, (p[0] + L_ * math.cos(e) * math.cos(a), p[1] + L_ * math.cos(e) * math.sin(a), p[2] + L_ * math.sin(e)),
                r, 0, n=3, tip=True)


def build(g):
    for (rings, tip), marks, band in zip(TRUNKS, MARKS, BAND):
        N.loft(g, "BirchBark", [N.ring(x, y, z, r, 6) for x, y, z, r in rings], top=tip)
        N.loft(g, "BirchMark", [_hex(rings, -0.55, 0.07), _hex(rings, band, 0.07)])
        for face, z0, z1 in marks:                 # 면 한 칸: 바깥 0.07 밖(줄기 면과 평행) · 안 0.15 속
            ks = (face, (face + 1) % 6)
            N.loft(g, "BirchMark", [_hex(rings, z0, 0.07, ks, 0.15), _hex(rings, z1, 0.07, ks, 0.15)])
        x, y, _, r = rings[0]
        N.cbox(x - r - 0.5, x + r + 0.5, y - r - 0.5, y + r + 0.5, 0, 8.0)
        lean = math.degrees(math.atan2(tip[1] - y, tip[0] - x))
        _fan(g, (tip[0], tip[1], tip[2] - 0.3), lean, FAN_TOP, 1.0)
    for p0, p1, r0, r1, s in LIMBS:
        N.stick(g, "BirchBark", p0, p1, r0, r1, n=4)
        az = math.degrees(math.atan2(p1[1] - p0[1], p1[0] - p0[0]))
        mid = tuple(p0[i] + 0.55 * (p1[i] - p0[i]) for i in range(3))
        _fan(g, mid, az, FAN_MID, s)
        _fan(g, tuple(p0[i] + 0.8 * (p1[i] - p0[i]) for i in range(3)), az, FAN_80, s)
        _fan(g, p1, az, FAN_END, s)
